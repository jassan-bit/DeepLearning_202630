def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("/tmp/e2-eda-current-v1"))
    args = parser.parse_args(argv)
    output = args.output.resolve()
    require(not args.output.is_symlink(), "Output directory cannot be a symlink")
    outputs = build(ROOT)
    # Validate every collision before writing anything. Existing unrelated
    # assets are left alone; a changed owned output requires a new directory.
    for name, raw in outputs.items():
        path = output / name
        require(not path.is_symlink(), "Output file cannot be a symlink")
        require(not path.exists() or (path.is_file() and path.read_bytes() == raw),
                "Refusing to overwrite changed output; select a new --output directory: " + name)
    output.mkdir(parents=True, exist_ok=True)
    for name, raw in outputs.items():
        path = output / name
        if not path.exists():
            path.write_bytes(raw)
    print(json.dumps({"version": VERSION, "output_files": list(outputs),
                      "profile_rows": 9, "stable_existing_outputs_accepted": True}, ensure_ascii=False))


if __name__ == "__main__":
    main()
